use std::collections::{BTreeSet, HashMap};
use std::io::Read;
use std::os::unix::ffi::OsStrExt;
use std::path::Path;

use anyhow::Result;

use crate::config::PluginSection;
use crate::core::model::{Pair, TreeEntry};
use crate::error::PluginError;
use crate::plugin::{
    Classifier, Items, PluginCall, ScopeResult, classifier_label, is_python_space, refuse_timeout,
};

const READ_LIMIT: u64 = 32 * 1024;

pub struct Generated {
    /// 直前の版の blob だけを覚えるのは，覚える量を 1 版の tree の大きさまでにするためである．
    /// 全部の版の blob を覚えると，数万の版で数百万の項目になりうる
    previous: HashMap<String, bool>,
}

impl Generated {
    pub fn new(section: &PluginSection) -> Result<Generated> {
        let label = classifier_label(section);
        refuse_timeout(&label, section)?;
        Items::new(label, section, &[])?;
        Ok(Generated {
            previous: HashMap::new(),
        })
    }
}

impl Classifier for Generated {
    fn name(&self) -> &'static str {
        "generated"
    }

    fn effective_config(&self) -> serde_json::Value {
        serde_json::json!({})
    }

    fn labels(&self) -> &'static [&'static str] {
        &[]
    }

    fn scope(&mut self, call: &PluginCall, tree: &[TreeEntry]) -> Result<ScopeResult, PluginError> {
        let mut seen = HashMap::new();
        let mut keep = BTreeSet::new();
        for entry in tree.iter().filter(|entry| entry.is_regular_file()) {
            call.interrupt.check().map_err(PluginError::Abort)?;
            let generated = match self.previous.get(&entry.oid).or(seen.get(&entry.oid)) {
                Some(&known) => known,
                None => {
                    let path = call
                        .work_tree
                        .join(std::ffi::OsStr::from_bytes(&entry.path));
                    has_marker(&path)?
                }
            };
            seen.insert(entry.oid.clone(), generated);
            if !generated {
                keep.insert(entry.path.clone());
            }
        }
        // 失敗したときに前の版を残すのは，やり直しでも読まずに済むファイルを増やすためである
        self.previous = seen;
        Ok(ScopeResult {
            keep: Some(keep),
            rows: Vec::new(),
        })
    }

    fn classify(&mut self, _pairs: &[Pair]) -> Result<Vec<&'static str>, PluginError> {
        unreachable!("generated gives no labels, so classify is not called")
    }
}

fn has_marker(path: &Path) -> Result<bool, PluginError> {
    let failed = |err: std::io::Error| PluginError::Failed {
        reason: format!("cannot read {}: {err}", path.display()),
    };
    let mut prefix = Vec::new();
    std::fs::File::open(path)
        .and_then(|file| file.take(READ_LIMIT).read_to_end(&mut prefix))
        .map_err(failed)?;
    Ok(marked(&prefix))
}

/// Python の casefold でなく Unicode の小文字にするのは，Rust の標準に casefold が無いからである．
/// 印は ASCII なので，違いが出るのは，合字のような文字で印を書いたファイルだけである．
fn marked(prefix: &[u8]) -> bool {
    let lowered = String::from_utf8_lossy(prefix)
        .to_lowercase()
        .replace('-', " ");
    let folded = lowered
        .split(is_python_space)
        .filter(|word| !word.is_empty())
        .collect::<Vec<_>>()
        .join(" ");
    let has = |marker: &str| folded.contains(marker);
    if has("<auto generated") || has("@generated") {
        return true;
    }
    if [
        "@jakarta.annotation.generated",
        "@javax.annotation.generated",
        "@javax.annotation.processing.generated",
    ]
    .into_iter()
    .any(has)
    {
        return true;
    }
    has("do not edit")
        && [
            "automatically generated",
            "auto generated",
            "code generated by",
            "this file was generated",
            "this class is generated",
        ]
        .into_iter()
        .any(has)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::core::model::ObjectKind;
    use crate::process::Interrupt;

    #[test]
    fn each_marker_is_found() {
        for text in [
            "// <auto-generated>\nclass A {}",
            "/* @Generated by tool */",
            "@javax.annotation.Generated(\"x\")",
            "@jakarta.annotation.Generated",
            "@javax.annotation.processing.Generated",
            "// DO NOT EDIT\n// This file was generated by protoc",
            "// do not\n\t edit: automatically   generated",
            "// Code generated by mockgen. DO NOT EDIT.",
            "// auto-generated; do not edit",
            "/* this class is generated. Do Not Edit */",
            "\u{1f}do\u{1c}not edit\nauto generated",
        ] {
            assert!(marked(text.as_bytes()), "{text:?}");
        }
    }

    #[test]
    fn near_misses_are_not_markers() {
        for text in [
            "class A {}",
            "// do not edit",
            "// automatically generated",
            "// generated",
            "// auto generation; do not edit",
            "@javax.annotation.Nonnull",
            "do not\u{200b}edit, auto generated",
        ] {
            assert!(!marked(text.as_bytes()), "{text:?}");
        }
    }

    #[test]
    fn only_the_first_32_kib_are_read() {
        let mut text = vec![b' '; READ_LIMIT as usize - 10];
        text.extend_from_slice(b"@generated");
        assert!(marked(&text));
        let dir = std::env::temp_dir().join(format!("cgweave-generated-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("in.java"), &text).unwrap();
        text.insert(0, b' ');
        std::fs::write(dir.join("out.java"), &text).unwrap();
        assert!(has_marker(&dir.join("in.java")).unwrap());
        assert!(!has_marker(&dir.join("out.java")).unwrap());
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn invalid_utf8_is_replaced_and_still_matched() {
        assert!(marked(b"\xff\xfe@generated"));
    }

    #[test]
    fn scope_reads_only_unknown_blobs_and_fails_on_unreadable_files() {
        let dir =
            std::env::temp_dir().join(format!("cgweave-generated-scope-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("Gen.java"), "// @generated\n").unwrap();
        std::fs::write(dir.join("A.java"), "class A {}\n").unwrap();
        let entry = |oid: &str, path: &str| TreeEntry {
            mode: 0o100644,
            kind: ObjectKind::Blob,
            oid: oid.repeat(40),
            path: path.as_bytes().to_vec(),
        };
        let interrupt = Interrupt::default();
        let call = PluginCall {
            commit: "c",
            work_tree: &dir,
            temp_dir: &dir,
            deadline: None,
            interrupt: &interrupt,
        };
        let mut plugin = Generated {
            previous: HashMap::new(),
        };
        let tree = [entry("1", "Gen.java"), entry("2", "A.java")];
        let keep = plugin.scope(&call, &tree).unwrap().keep.unwrap();
        assert_eq!(keep.into_iter().collect::<Vec<_>>(), [b"A.java".to_vec()]);

        // 同じ blob のファイルは読まないので，消しても前の結果で決まる
        std::fs::remove_file(dir.join("Gen.java")).unwrap();
        let tree = [entry("1", "Gen.java"), entry("2", "A.java")];
        let keep = plugin.scope(&call, &tree).unwrap().keep.unwrap();
        assert_eq!(keep.len(), 1);

        let tree = [entry("3", "Gen.java")];
        match plugin.scope(&call, &tree) {
            Err(PluginError::Failed { reason }) => {
                assert!(reason.starts_with("cannot read "), "{reason}");
                assert!(reason.contains("Gen.java"), "{reason}");
            }
            _ => panic!("an unreadable file must fail"),
        }
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
